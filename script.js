// State Management
let currentLanguage = 'en';
let currentTheme = 'light';
let filteredZodiacs = [...zodiacData];

// DOM Elements
const zodiacGrid = document.getElementById('zodiacGrid');
const searchInput = document.getElementById('searchInput');
const elementFilter = document.getElementById('elementFilter');
const langToggle = document.getElementById('langToggle');
const themeToggle = document.getElementById('themeToggle');
const detailPanel = document.getElementById('detailPanel');
const overlay = document.getElementById('overlay');
const closePanel = document.getElementById('closePanel');

// Initialize App
function init() {
    loadPreferences();
    applyTheme();
    applyLanguage();
    renderZodiacs();
    attachEventListeners();
}

// Load saved preferences from localStorage
function loadPreferences() {
    const savedLang = localStorage.getItem('zodiac-language');
    const savedTheme = localStorage.getItem('zodiac-theme');
    const savedFilter = localStorage.getItem('zodiac-filter');
    const savedSearch = localStorage.getItem('zodiac-search');

    if (savedLang) currentLanguage = savedLang;
    if (savedTheme) currentTheme = savedTheme;
    if (savedFilter) elementFilter.value = savedFilter;
    if (savedSearch) searchInput.value = savedSearch;
}

// Save preferences to localStorage
function savePreferences() {
    localStorage.setItem('zodiac-language', currentLanguage);
    localStorage.setItem('zodiac-theme', currentTheme);
    localStorage.setItem('zodiac-filter', elementFilter.value);
    localStorage.setItem('zodiac-search', searchInput.value);
}

// Apply Theme
function applyTheme() {
    document.body.setAttribute('data-theme', currentTheme);
    const themeIcon = themeToggle.querySelector('.theme-icon');
    themeIcon.textContent = currentTheme === 'light' ? '🌙' : '☀️';
}

// Toggle Theme
function toggleTheme() {
    currentTheme = currentTheme === 'light' ? 'dark' : 'light';
    applyTheme();
    savePreferences();
}

// Apply Language
function applyLanguage() {
    const langElements = document.querySelectorAll('[data-lang-en]');
    langElements.forEach(el => {
        const enText = el.getAttribute('data-lang-en');
        const zhText = el.getAttribute('data-lang-zh');
        el.textContent = currentLanguage === 'en' ? enText : zhText;
    });

    // Update placeholders
    const placeholderElements = document.querySelectorAll('[data-placeholder-en]');
    placeholderElements.forEach(el => {
        const enPlaceholder = el.getAttribute('data-placeholder-en');
        const zhPlaceholder = el.getAttribute('data-placeholder-zh');
        el.placeholder = currentLanguage === 'en' ? enPlaceholder : zhPlaceholder;
    });

    // Update select options
    const optionElements = document.querySelectorAll('option[data-lang-en]');
    optionElements.forEach(el => {
        const enText = el.getAttribute('data-lang-en');
        const zhText = el.getAttribute('data-lang-zh');
        el.textContent = currentLanguage === 'en' ? enText : zhText;
    });

    // Update language toggle button
    langToggle.querySelector('.lang-text').textContent = currentLanguage === 'en' ? '中文' : 'EN';

    // Re-render if detail panel is open
    if (detailPanel.classList.contains('active')) {
        const zodiacId = parseInt(detailPanel.getAttribute('data-zodiac-id'));
        const zodiac = zodiacData.find(z => z.id === zodiacId);
        if (zodiac) {
            updateDetailPanel(zodiac);
        }
    }

    // Re-render zodiac cards to update tooltips
    renderZodiacs();
}

// Toggle Language
function toggleLanguage() {
    currentLanguage = currentLanguage === 'en' ? 'zh' : 'en';
    applyLanguage();
    savePreferences();
}

// Filter Zodiacs
function filterZodiacs() {
    const searchTerm = searchInput.value.toLowerCase().trim();
    const selectedElement = elementFilter.value;

    filteredZodiacs = zodiacData.filter(zodiac => {
        const matchesSearch = searchTerm === '' ||
            zodiac.name.toLowerCase().includes(searchTerm) ||
            zodiac.nameZh.includes(searchTerm) ||
            zodiac.trait.toLowerCase().includes(searchTerm) ||
            zodiac.traitZh.includes(searchTerm);

        const matchesElement = selectedElement === 'all' || zodiac.element === selectedElement;

        return matchesSearch && matchesElement;
    });

    renderZodiacs();
    savePreferences();
}

// Render Zodiac Cards
function renderZodiacs() {
    zodiacGrid.innerHTML = '';

    if (filteredZodiacs.length === 0) {
        zodiacGrid.innerHTML = `
            <div class="empty-state">
                ${currentLanguage === 'en' ? 'No zodiacs found. Try adjusting your filters.' : '未找到生肖。请调整筛选条件。'}
            </div>
        `;
        return;
    }

    filteredZodiacs.forEach((zodiac, index) => {
        const card = document.createElement('div');
        card.className = 'zodiac-card';
        card.style.animationDelay = `${index * 0.05}s`;
        
        const elementText = currentLanguage === 'en' ? zodiac.element : zodiac.elementZh;
        const traitText = currentLanguage === 'en' ? zodiac.trait : zodiac.traitZh;

        card.innerHTML = `
            <div class="zodiac-icon">${zodiac.icon}</div>
            <h3 class="zodiac-name">${currentLanguage === 'en' ? zodiac.name : zodiac.nameZh}</h3>
            <p class="zodiac-name-zh">${currentLanguage === 'en' ? zodiac.nameZh : zodiac.name}</p>
            <span class="zodiac-element">${elementText}</span>
            <div class="tooltip">${traitText}</div>
        `;

        card.addEventListener('click', () => showDetail(zodiac));
        zodiacGrid.appendChild(card);
    });
}

// Show Detail Panel
function showDetail(zodiac) {
    updateDetailPanel(zodiac);
    detailPanel.classList.add('active');
    overlay.classList.add('active');
    detailPanel.setAttribute('data-zodiac-id', zodiac.id);
    document.body.style.overflow = 'hidden';
}

// Update Detail Panel Content
function updateDetailPanel(zodiac) {
    const detailIcon = document.getElementById('detailIcon');
    const detailName = document.getElementById('detailName');
    const detailNameZh = document.getElementById('detailNameZh');
    const detailElement = document.getElementById('detailElement');
    const detailDescription = document.getElementById('detailDescription');

    detailIcon.textContent = zodiac.icon;
    
    if (currentLanguage === 'en') {
        detailName.textContent = zodiac.name;
        detailNameZh.textContent = zodiac.nameZh;
        detailElement.textContent = `${zodiac.element} Element`;
        detailDescription.textContent = zodiac.description;
    } else {
        detailName.textContent = zodiac.nameZh;
        detailNameZh.textContent = zodiac.name;
        detailElement.textContent = `${zodiac.elementZh}元素`;
        detailDescription.textContent = zodiac.descriptionZh;
    }
}

// Close Detail Panel
function closeDetail() {
    detailPanel.classList.remove('active');
    overlay.classList.remove('active');
    document.body.style.overflow = '';
}

// Attach Event Listeners
function attachEventListeners() {
    searchInput.addEventListener('input', filterZodiacs);
    elementFilter.addEventListener('change', filterZodiacs);
    langToggle.addEventListener('click', toggleLanguage);
    themeToggle.addEventListener('click', toggleTheme);
    closePanel.addEventListener('click', closeDetail);
    overlay.addEventListener('click', closeDetail);

    // Keyboard shortcuts
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && detailPanel.classList.contains('active')) {
            closeDetail();
        }
    });

    // Initial filter
    filterZodiacs();
}

// Initialize on DOM Load
document.addEventListener('DOMContentLoaded', init);
